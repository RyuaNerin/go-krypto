package drbg_test

import (
	"crypto/sha256"
	"encoding/hex"
	"fmt"

	"github.com/RyuaNerin/go-krypto/drbg"
	"github.com/RyuaNerin/go-krypto/lea"
)

func ExampleNewHashDRBG() {
	generator, err := drbg.NewHashDRBG(
		sha256.New(),
		drbg.WithPersonalizationString([]byte("my personalization")),
		drbg.WithDerivationFunction(true), // Enable the derivation function
	)
	if err != nil {
		panic(err)
	}
	defer generator.Zeroize()

	var randomBytes [32]byte
	n, err := generator.Read(randomBytes[:])
	if err != nil {
		panic(err)
	}
	fmt.Println("Hash DRBG generated bytes:", n)
	fmt.Println(hex.Dump(randomBytes[:]))
}

