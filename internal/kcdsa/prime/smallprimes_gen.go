//go:build ignore

package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
)

func main() {
	limit := flag.Int("limit", 1<<16, "upper limit for small primes")
	pkg := flag.String("pkg", "internal", "package name")
	out := flag.String("out", "smallprimes.go", "output file")
	flag.Parse()

	composite := make([]bool, *limit+1)
	for i := 2; i*i <= *limit; i++ {
		if composite[i] {
			continue
		}
		for j := i * i; j <= *limit; j += i {
			composite[j] = true
		}
	}

	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by smallprimes_gen.go; DO NOT EDIT.\n\n")
	fmt.Fprintf(&buf, "package %s\n\n", *pkg)
	fmt.Fprintf(&buf, "var smallPrimes = [...]uint16{")

	n := 0
	for i := 3; i <= *limit; i += 2 {
		if composite[i] {
			continue
		}
		if n%12 == 0 {
			buf.WriteString("\n\t")
		}
		fmt.Fprintf(&buf, "%d, ", i)
		n++
	}
	buf.WriteString("\n}\n")

	src, err := format.Source(buf.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
	log.Printf("%s: %d small primes written", *out, n)
}
